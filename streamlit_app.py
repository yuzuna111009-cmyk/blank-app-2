import streamlit as st

st.set_page_config(page_title="レポート構成アドバイザー", page_icon="📝")

st.title("📝 レポート構成アドバイザー")
st.write("レポートのテーマと種類を選ぶと、構成案・注意点・文字数目安を提示します。")

# --- 入力 ---
theme = st.text_input("レポートのテーマを入力してください")

report_type = st.selectbox(
    "レポートの種類を選んでください",
    ["調査レポート", "考察レポート", "実験・実習レポート"]
)

if st.button("構成案を作成する") and theme:
    st.subheader("📄 レポート構成案")

    st.markdown("### ① はじめに（導入）【200〜300字】")
    st.write(f"- テーマ「{theme}」を選んだ理由を書く")
    st.write("- 本レポートで何を明らかにするのかを示す")
    st.write("❌ よくあるミス：いきなり結論を書く、背景説明がない")

    st.markdown("### ② 背景・基礎知識【400〜600字】")
    st.write("- テーマに関する基本的な用語や理論を説明する")
    st.write("- 信頼できる資料や文献を簡潔にまとめる")
    st.write("❌ よくあるミス：出典が不明、説明が長すぎる")

    if report_type == "調査レポート":
        st.markdown("### ③ 調査内容・分析【800〜1200字】")
        st.write("- 調査方法や集めたデータを説明する")
        st.write("- 結果を客観的に分析する")
        st.write("❌ よくあるミス：調査結果と感想が混ざっている")

    elif report_type == "考察レポート":
        st.markdown("### ③ 本論・考察【800〜1200字】")
        st.write("- テーマについての主張を論理的に展開する")
        st.write("- 具体例や資料を根拠として用いる")
        st.write("❌ よくあるミス：根拠のない意見だけを書く")

    else:  # 実験・実習レポート
        st.markdown("### ③ 実験・実習内容【600〜1000字】")
        st.write("- 実験の目的、方法、手順を簡潔にまとめる")
        st.write("- 図や表を用いて結果を示す")
        st.write("❌ よくあるミス：手順が曖昧、結果が文章だけ")

    st.markdown("### ④ まとめ・結論【200〜300字】")
    st.write("- 全体の内容を簡潔に振り返る")
    st.write("- 今後の課題や展望を述べる")
    st.write("❌ よくあるミス：新しい内容をここで書く")

    st.info("※ この構成は一例です。授業の指示に応じて調整してください。")
